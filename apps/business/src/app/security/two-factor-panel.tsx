'use client';

import { useRouter } from 'next/navigation';
import { useState, type FormEvent } from 'react';
import { TEXT } from '@/text';
import { post } from '../client';
import { ui } from '../ui';

type Setup = { secret: string; qrSvg: string };

/** Turn two-step sign-in on (scan, then confirm with a code) or off (password + code). */
export function TwoFactorPanel({ on }: { on: boolean }) {
  const router = useRouter();
  const [setup, setSetup] = useState<Setup>();
  const [code, setCode] = useState('');
  const [password, setPassword] = useState('');
  const [error, setError] = useState<string>();
  const [busy, setBusy] = useState(false);

  async function run(action: () => Promise<void>) {
    setBusy(true);
    setError(undefined);
    try {
      await action();
    } catch (err) {
      setError(err instanceof Error ? err.message : TEXT.common.failed);
    } finally {
      setBusy(false);
    }
  }

  const finish = () => {
    setSetup(undefined);
    setCode('');
    setPassword('');
    router.refresh();
  };

  const errorLine = error && (
    <p role="alert" style={ui.error}>
      {error}
    </p>
  );
  const codeInput = (
    <label style={ui.label}>
      {TEXT.login.code}
      <input
        style={ui.input}
        inputMode="numeric"
        autoComplete="one-time-code"
        maxLength={6}
        value={code}
        onChange={(e) => setCode(e.target.value)}
        required
      />
    </label>
  );

  if (on) {
    const submit = (e: FormEvent) => {
      e.preventDefault();
      return run(async () => {
        await post('/api/auth/two-factor/disable', { password, code });
        finish();
      });
    };
    return (
      <form onSubmit={submit}>
        <p style={ui.muted}>{TEXT.twoFactor.offHelp}</p>
        <label style={ui.label}>
          {TEXT.login.password}
          <input
            style={ui.input}
            type="password"
            autoComplete="current-password"
            value={password}
            onChange={(e) => setPassword(e.target.value)}
            required
          />
        </label>
        {codeInput}
        {errorLine}
        <button type="submit" disabled={busy} style={ui.primary}>
          {TEXT.twoFactor.turnOff}
        </button>
      </form>
    );
  }

  if (!setup) {
    return (
      <>
        {errorLine}
        <button
          type="button"
          disabled={busy}
          style={ui.secondary}
          onClick={() => run(async () => setSetup(await post<Setup>('/api/auth/two-factor/setup')))}
        >
          {TEXT.twoFactor.start}
        </button>
      </>
    );
  }

  const confirm = (e: FormEvent) => {
    e.preventDefault();
    return run(async () => {
      await post('/api/auth/two-factor/confirm', { code });
      finish();
    });
  };
  return (
    <form onSubmit={confirm}>
      <p>{TEXT.twoFactor.scan}</p>
      {/* The SVG is generated by our own server from the otpauth URL. */}
      <div style={{ width: 200 }} dangerouslySetInnerHTML={{ __html: setup.qrSvg }} />
      <p>
        <code>{setup.secret}</code>
      </p>
      {codeInput}
      {errorLine}
      <button type="submit" disabled={busy} style={ui.primary}>
        {TEXT.twoFactor.confirm}
      </button>
    </form>
  );
}
